"""
Django Admin for the Materials and Vendor masters.

WHAT THIS IS — AND IS NOT
    Scaffolding. It exists so master data can be entered, corrected and checked
    long before the real screens are built. It is NOT the interface designed in
    BOM_Prototype.html — that arrives with the BOM and PO screens.

    Everything here is generated by Django from the models, which is why it
    looks the way it does. It is worth making usable, because this is where the
    data will be maintained for the next few weeks.

EDITING FROM THE LIST
    Fields in `list_editable` can be changed straight from the list, several
    rows at a time, then saved in one go. Much faster than opening 705 materials
    one by one. Everything else is edited by clicking into the record.
"""
from django.contrib import admin
from django.db.models import Count
from django.utils.html import format_html

from .models import (Material, MaterialGroup, UnitOfMeasure, Vendor, VendorCategory,
                     VendorGroup, VendorRate)


@admin.register(MaterialGroup)
class MaterialGroupAdmin(admin.ModelAdmin):
    """The Group master — AG1, PL3, EL2 and the rest."""
    list_display = ("code", "name", "is_stock_item", "material_count")
    list_editable = ("name", "is_stock_item")
    list_display_links = ("code",)
    search_fields = ("code", "name")
    list_filter = ("is_stock_item",)
    ordering = ("code",)

    def get_queryset(self, request):
        # Counted in the database rather than per row, so the page stays fast.
        return super().get_queryset(request).annotate(_materials=Count("materials"))

    @admin.display(description="Materials", ordering="_materials")
    def material_count(self, obj):
        """How many materials sit in this group. A group with 0 can be deleted."""
        return obj._materials


@admin.register(Material)
class MaterialAdmin(admin.ModelAdmin):
    list_display = ("code", "name", "specification", "group", "home_activity", "also_used_in",
                    "uom", "estimation_rate", "gst_percent", "hsn_code", "is_common", "is_active")
    # Everything the data-entry work actually needs, editable straight from the list.
    list_editable = ("specification", "uom", "estimation_rate", "gst_percent",
                     "hsn_code", "is_common", "is_active")
    list_display_links = ("code",)
    # ⚠ Filter on the COLUMNS, not the dead link table. `activity_links` still
    #   exists as a relation but nothing reads it, so filtering by it would
    #   quietly answer a question about data the app has stopped using.
    list_filter = ("group", "uom", "is_common", "is_active", "home_activity")
    search_fields = ("code", "name", "search_aliases", "specification")
    list_per_page = 50
    save_on_top = True
    fieldsets = (
        ("Identity", {
            "fields": ("code", "name", "group", "subgroup", "specification", "search_aliases"),
            "description": "The code is generated as ACTIVITY-GROUP-SERIAL and never changes, "
                           "even if the material is later reclassified.",
        }),
        ("Pricing & tax", {
            "fields": ("uom", "estimation_rate", "gst_percent", "hsn_code"),
            "description": "The estimation rate drives the BOQ and the BOM budget. It is not a "
                           "vendor price — those live on the vendor.",
        }),
        ("Stock", {"fields": ("reorder_level", "current_stock")}),
        ("Status", {
            "fields": ("is_common", "is_active"),
            "description": "Common materials appear in every activity's list, whatever their "
                           "home activity.",
        }),
    )

    def get_queryset(self, request):
        # ⚠ select_related on the COLUMNS, not a prefetch of the dead link table.
        return (super().get_queryset(request)
                .select_related("group", "home_activity", "also_used_in"))

    # ⚠ THERE WAS A METHOD CALLED `home_activity` HERE AND IT HAD TO GO.
    #
    #   It read the old link table and, being a method, it SHADOWED the real
    #   field of the same name added in slice 8. So `list_display` resolved to
    #   the method rather than the column, and every material created after
    #   slice 8 — which has a real home activity and no link row — displayed as
    #   a red "none". The data was right; the screen was reading the wrong place.
    #
    #   Deleting it is the fix: `home_activity` and `also_used_in` are ordinary
    #   foreign keys and Admin renders them without help.


# ⚠ THE VendorCategory INLINE WAS REMOVED FROM VendorAdmin IN SLICE 8.
