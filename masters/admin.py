@admin.register(UnitOfMeasure)
class UnitOfMeasureAdmin(admin.ModelAdmin):
    """
    The unit vocabulary. Editable because it has to be — a unit missing from
    here means somebody's spreadsheet row is rejected and they can do nothing
    about it but telephone you.

    ⚠ The guards live on the model, not here, so they hold for the import and
      any future screen as well: a code cannot change once materials carry it,
      a delete is refused while anything uses it, and a new code close to an
      existing one is refused with the existing one named.
    """
    list_display = ("code", "name", "aliases", "materials_using", "is_active", "sort_order")
    list_editable = ("name", "aliases", "is_active", "sort_order")
    list_display_links = ("code",)
    list_filter = ("is_active",)
    search_fields = ("code", "name", "aliases")
    ordering = ("sort_order", "code")

    @admin.display(description="Materials using it")
    def materials_using(self, unit):
        count = unit.in_use
        return count or format_html('<span style="color:#6B7280">—</span>')


@admin.register(VendorGroup)
class VendorGroupAdmin(admin.ModelAdmin):
    """
    WHAT A VENDOR IS — the master the vendor screen's Group dropdown reads.

    ⚠ THIS IS THE LIVE ONE. `VendorCategory` below it is deliberately NOT
      registered any more; see the note there. Getting these two the wrong way
      round is exactly what happened first: the dead table was editable in
      Admin and this one was not registered at all, so the Master data tile
      pointing at it returned a 404. Found by checking, not by reading.

    ⚠ A GROUP IS NOT AN ACTIVITY. Saahil, after we looked at all 37 old values
      together: "lets use vendor category as an identifier to search vendor …
      lets not mix vendor category and link them to Vendor Activities."

      The list is a mix of material types (Cement, Red Bricks), services
      (Fabricator, Piling), consultants (Structure Engineer) and a utility
      (Torrent Power). It answers WHAT A VENDOR IS, in the words somebody would
      search with. `Vendor.activity_1/2` answers WHICH TRADE THEY SERVE. Two
      questions, two fields, and merging them loses the ability to ask either.
    """
    list_display = ("name", "vendor_count", "is_active")
    list_display_links = ("name",)
    list_editable = ("is_active",)
    search_fields = ("name",)
    ordering = ("name",)

    def get_queryset(self, request):
        # One grouped count, not one query per row.
        return super().get_queryset(request).annotate(n=Count("vendors"))

    @admin.display(description="Vendors", ordering="n")
    def vendor_count(self, group):
        return group.n


# ⚠ `VendorCategory` IS DELIBERATELY NOT REGISTERED, AND MUST NOT BE.
#
#   It is the mechanism VendorGroup replaced: a row per vendor per free-text
#   string, no controlled list, nothing stopping "General Contruction Material"
#   existing on six vendors. The slice 8 migration read its 185 rows once, built
#   the 36-name master out of them, corrected the spellings and set each
#   vendor's group. NOTHING HAS READ IT SINCE.
#
#   Leaving it registered was worse than useless: somebody could open a vendor,
#   add a category, save, and nothing whatsoever would happen — the silent
#   version of the two-places-disagreeing problem that took "Contractor" out of
#   this table in the first place.
#
#   The TABLE and its rows are untouched, so the migration still has something to
#   be checked against. Dropping it is a later migration, once the seed commands
#   and the importer stop referencing it.


